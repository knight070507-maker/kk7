// 获取所有成分的数组
export const allIngredients: Ingredient[] = Object.values(ingredientDB);

// 按分类获取成分
export function getIngredientsByCategory(category: string): Ingredient[] {
  return allIngredients.filter((ing) => ing.category === category);
}

// 按风险等级获取成分
export function getIngredientsByRisk(level: number): Ingredient[] {
  return allIngredients.filter((ing) => ing.riskLevel === level);
}

// 根据ID获取成分
export function getIngredientById(id: string): Ingredient | undefined {
  return ingredientDB[id];
}

// 根据多个ID获取成分列表
export function getIngredientsByIds(ids: string[]): Ingredient[] {
  return ids.map((id) => ingredientDB[id]).filter(Boolean);
}
